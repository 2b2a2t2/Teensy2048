#!/usr/bin/env python3
"""Merge empirical counts + literature adjustments -> genre_data.h + GENRE_DATA.md."""

import json
from pathlib import Path

import literature as LIT

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]  # repo root
MIN_ROW = 20  # samples below this -> fallback to pooled prior

F_ESTIMATED = 0x01
F_TRANS_FB = 0x02
F_QUAL_FB = 0x04
F_INV_FB = 0x08


def normalize(weights):
    """Largest-remainder scaling to integers summing to exactly 100."""
    tot = sum(weights)
    if tot <= 0:
        return None
    raw = [w * 100.0 / tot for w in weights]
    base = [int(x) for x in raw]
    rem = 100 - sum(base)
    order = sorted(range(len(raw)), key=lambda i: raw[i] - base[i], reverse=True)
    for i in range(rem):
        base[order[i]] += 1
    return base


def uniform(n):
    return normalize([1] * n)


def blank_grid(rows, cols):
    return [[0] * cols for _ in range(rows)]


def add_grid(dst, src):
    for r in src:
        for k, v in r.items():
            a, b = map(int, k.split("->"))
            dst[a][b] += v


def pooled_grid(results, field, keys, rows, cols):
    g = blank_grid(rows, cols)
    for name in keys:
        for k, v in results[name][field].items():
            a, b = map(int, k.split("->"))
            g[a][b] += v
    return g


def row_or_fallback(weights, prior, flags, bit):
    """Normalize one row; fall back to prior row when too few samples."""
    if sum(weights) < MIN_ROW:
        row = normalize(prior)
        if row is None:
            row = uniform(len(weights))
        flags[0] |= bit
        return row
    row = normalize(weights)
    return row if row is not None else uniform(len(weights))


def build_genres(results):
    all_emp = [k for g in LIT.EMPIRICAL.values() for k in g]
    pooled_trans = pooled_grid(results, "trans", all_emp, 7, 7)
    pooled_qual = pooled_grid(results, "qual", all_emp, 7, 4)
    pooled_inv = pooled_grid(results, "inv", all_emp, 7, 4)

    genres = {}
    for g in LIT.GENRE_ORDER:
        flags = [0]
        tmb = LIT.TRANS_MULT.get(g, {})
        qmb = LIT.QUAL_MULT.get(g, [1.0] * 4)
        imb = LIT.INV_MULT.get(g, [1.0] * 4)

        if g in LIT.HAND:
            h = LIT.HAND[g]
            trans = [row[:] for row in h["trans"]]
            qual = [row[:] for row in h["qual"]]
            inv = [row[:] for row in h["inv"]]
            prior_t, prior_q, prior_i = trans, qual, inv
            flags[0] |= F_ESTIMATED
            stats = {"pieces": 0, "events": 0, "chrom": 0.0, "sources": []}
        elif g in LIT.EMPIRICAL:
            srcs = LIT.EMPIRICAL[g]
            trans = pooled_grid(results, "trans", srcs, 7, 7)
            qual = pooled_grid(results, "qual", srcs, 7, 4)
            inv = pooled_grid(results, "inv", srcs, 7, 4)
            prior_t, prior_q, prior_i = pooled_trans, pooled_qual, pooled_inv
            stats = {"pieces": 0, "events": 0, "chrom": 0.0, "sources": srcs}
            for s in srcs:
                stats["pieces"] += results[s]["pieces"]
                stats["events"] += results[s]["events"]
            chrom = sum(results[s]["chromatic_rate"] * results[s]["transitions"]
                        for s in srcs)
            tr = sum(results[s]["transitions"] for s in srcs)
            stats["chrom"] = chrom / tr if tr else 0.0
        else:
            flags[0] |= F_ESTIMATED
            # pop-family prior x style multipliers
            trans = [[pooled_trans[a][b] * tmb.get((a, b), 1.0)
                      for b in range(7)] for a in range(7)]
            qual = [[pooled_qual[a][b] * qmb[b] for b in range(4)]
                    for a in range(7)]
            inv = [[pooled_inv[a][b] * imb[b] for b in range(4)]
                   for a in range(7)]
            prior_t, prior_q, prior_i = pooled_trans, pooled_qual, pooled_inv
            stats = {"pieces": 0, "events": 0, "chrom": 0.0, "sources": []}

        tr_rows = [row_or_fallback(trans[a], prior_t[a], flags, F_TRANS_FB)
                   for a in range(7)]
        q_rows = [row_or_fallback(qual[a], prior_q[a], flags, F_QUAL_FB)
                  for a in range(7)]
        i_rows = [row_or_fallback(inv[a], prior_i[a], flags, F_INV_FB)
                  for a in range(7)]
        rw = LIT.RHYTHM_W[g]
        assert sum(rw) == 100
        genres[g] = {
            "trans": tr_rows, "qual": q_rows, "inv": i_rows,
            "rhythmW": rw, "microVar": LIT.MICRO_VAR[g],
            "flags": flags[0], "stats": stats,
        }
    return genres


def emit_header(genres, out_path):
    lines = []
    a = lines.append
    a("// genre_data.h — generated by tools/genre_data/generate.py; DO NOT EDIT.")
    a("// Source counts: tools/genre_data/results.json; method: GENRE_DATA.md.")
    a("#ifndef GENRE_DATA_H")
    a("#define GENRE_DATA_H")
    a("#include <stdint.h>")
    a("")
    a(f"#define GENRE_COUNT {len(LIT.GENRE_ORDER)}")
    a(f"#define RHYTHM_COUNT {len(LIT.RHYTHM_TEMPLATES)}")
    a("#define GENRE_F_ESTIMATED 0x01")
    a("#define GENRE_F_TRANS_FB  0x02")
    a("#define GENRE_F_QUAL_FB   0x04")
    a("#define GENRE_F_INV_FB    0x08")
    a("")
    a("typedef struct {")
    a("  uint8_t trans[7][7];  // from-degree -> to-degree, row sum 100")
    a("  uint8_t qual[7][4];   // per degree: triad, 7th, 9th+, sus/alt")
    a("  uint8_t inv[7][4];    // per degree: root, 1st, 2nd, 3rd-in-bass")
    a("  uint8_t rhythmW[8];   // attack-template weights, sum 100")
    a("  uint8_t microVar;     // 0-255 humanization/feel amount")
    a("  uint8_t flags;        // GENRE_F_*")
    a("} GenreData;")
    a("")
    a("static const uint16_t rhythmMasks[RHYTHM_COUNT] = {")
    a("  " + ", ".join(f"0x{m:04X}" for _, m in LIT.RHYTHM_TEMPLATES) + "")
    a("};")
    a("static const char *const rhythmNames[RHYTHM_COUNT] = {")
    a("  " + ", ".join(f'"{n}"' for n, _ in LIT.RHYTHM_TEMPLATES))
    a("};")
    a("static const char *const genreNames[GENRE_COUNT] = {")
    a("  " + ", ".join(f'"{g}"' for g in LIT.GENRE_ORDER))
    a("};")
    a("")
    a("static const GenreData genreTable[GENRE_COUNT] = {")
    for g in LIT.GENRE_ORDER:
        d = genres[g]
        a(f"  {{ // {g}")
        rows = []
        for r in d["trans"]:
            rows.append("{" + ",".join(f"{v}" for v in r) + "}")
        a("    {" + ",".join(rows) + "},")
        rows = ["{" + ",".join(f"{v}" for v in r) + "}" for r in d["qual"]]
        a("    {" + ",".join(rows) + "},")
        rows = ["{" + ",".join(f"{v}" for v in r) + "}" for r in d["inv"]]
        a("    {" + ",".join(rows) + "},")
        a("    {" + ",".join(str(v) for v in d["rhythmW"]) + "},")
        a(f"    {d['microVar']}, 0x{d['flags']:02X}")
        a("  },")
    a("};")
    a("")
    a("#endif  // GENRE_DATA_H")
    out_path.write_text("\n".join(lines) + "\n")


def emit_markdown(genres, results, out_path):
    md = []
    a = md.append
    a("# Genre Data Tables")
    a("")
    a("Generated artefacts for KEYMODE chord/track helpers. Everything below is")
    a("produced by `tools/genre_data/` (Python 3 stdlib only); re-run the")
    a("pipeline to regenerate:")
    a("")
    a("```")
    a("python3 fetch.py && python3 process.py && python3 generate.py && python3 verify.py")
    a("```")
    a("")
    a("## What is in `genre_data.h`")
    a("")
    a(f"`GenreData genreTable[{len(LIT.GENRE_ORDER)}]` in PROGMEM-style const storage, per genre:")
    a("")
    a("| Field | Size | Meaning |")
    a("|---|---|---|")
    a("| `trans[7][7]` | 49 B | next-chord probabilities, rows = from-degree, row sum 100 |")
    a("| `qual[7][4]` | 49 B | quality buckets (triad / 7th / 9th+ / sus-alt) per degree, row sum 100 |")
    a("| `inv[7][4]` | 49 B | inversion buckets (root / 1st / 2nd / 3rd) per degree, row sum 100 |")
    a("| `rhythmW[8]` | 8 B | weights over `rhythmMasks`, sum 100 |")
    a("| `microVar` | 1 B | humanization amount 0-255 |")
    a("| `flags` | 1 B | `0x01` estimated, `0x02/0x04/0x08` row fallback used |")
    a("")
    total = 49 * 3 + 8 + 2
    n_gen = len(LIT.GENRE_ORDER)
    a(f"Struct size: {total} B x {n_gen} genres = {total * n_gen} B.")
    a("")
    a("Rhythm templates (16th-grid attack masks, one bar = 16 sixteenths):")
    a("")
    a("| # | Name | Mask | Attacks |")
    a("|---|---|---|---|")
    for i, (n, m) in enumerate(LIT.RHYTHM_TEMPLATES):
        steps = [str(s) for s in range(16) if m & (1 << s)]
        a(f"| {i} | {n} | `0x{m:04X}` | {', '.join(steps)} |")
    a("")
    a("## Method")
    a("")
    a("1. Parse chord + key annotations per corpus (Harte, jazz, ABC, Humdrum).")
    a("2. Key/scale detection: Krumhansl-Schmuckler correlation against")
    a("   major/minor key profiles; drop threshold `KS_MIN_CORR = 0.55`")
    a("   (weimar/TAVERN ship explicit keys; others fall back to K-S).")
    a("3. Map each chord to a scale degree 0-6 (I ii iii IV V vi vii);")
    a("   chromatic chords snap to the nearest in-scale degree.")
    a("4. Count transitions / quality buckets / inversion buckets per corpus.")
    a("   Inversions follow the Harte default: an absent bass annotation")
    a("   means root position; explicit non-chord-tone basses (`/9` etc.)")
    a("   are not counted as inversions. Corpora that only annotate")
    a("   non-root basses (Isophonics, TAVERN, Nottingham) therefore get")
    a("   implicit roots; the Weimar jazz DB rarely carries bass info, so")
    a("   its inv rows are root-dominated rather than measured.")
    a("5. Normalise every row with largest remainder to integer sum 100.")
    a("   Rows with < 20 samples fall back to the pooled empirical row, then")
    a("   to uniform, and set a fallback flag.")
    a("")
    a("Empirical genres use their corpus counts as-is. Hybrid genres")
    a("(COUNTRY, BLUES, RNB, FUNK, METAL, HIPHOP, ELECTRONIC, REGGAE) multiply")
    a("a pooled POP+ROCK+FOLK prior by style multipliers from genre literature.")
    a("Estimated genres (GOSPEL, LATIN, CINEMATIC, MODAL) use the same")
    a("machinery and are flagged `GENRE_F_ESTIMATED`.")
    a("Hand-authored genres (DUBTECHNO) ship full rows written straight from")
    a("genre theory in `literature.py` (`HAND`) - no corpus, no prior - and")
    a("are flagged `GENRE_F_ESTIMATED` too.")
    a("")
    a("Rhythm weights and `microVar` are hand-authored judgements for all")
    a("genres (no rhythm corpus); see `tools/genre_data/literature.py`.")
    a("")
    a("## Corpora")
    a("")
    a("| Source | Genre | License | Pieces | Chord events | Chromatic |")
    a("|---|---|---|---|---|---|")
    src = json.loads((HERE / "sources.json").read_text())
    # results source -> sources.json entry (or entries) it was built from
    lic_of = {
        "POP_billboard": ["billboard_lab"],
        "POP_isophonics": ["isophonics_caroleking"],
        "ROCK_isophonics": ["isophonics_beatles", "isophonics_queen"],
        "JAZZ_weimar": ["wjazzd"],
        "CLASSICAL_tavern": ["tavern"],
        "FOLK_nottingham": ["nottingham"],
    }

    def license_for(res_key):
        vals = []
        for k in lic_of[res_key]:
            v = src["included"][k].get("license", "?")
            if v not in vals:
                vals.append(v)
        return "; ".join(vals)

    for g, srcs in LIT.EMPIRICAL.items():
        for s in srcs:
            d = results[s]
            a(f"| {s} | {g} | {license_for(s)} | {d['pieces']} | "
              f"{d['events']} | {d['chromatic_rate']:.1%} |")
    a("")
    a("Excluded sources: " +
      "; ".join(f"{k} ({v.get('license', '?')}) — {v.get('reason', '')}"
                for k, v in src["excluded"].items()) + ".")
    a("")
    a("## Per-genre output")
    a("")
    a("| Genre | Tier | Events | Chromatic | Flags | rhythmW | microVar |")
    a("|---|---|---|---|---|---|---|")
    for g in LIT.GENRE_ORDER:
        d = genres[g]
        st = d["stats"]
        tier = ("empirical" if g in LIT.EMPIRICAL else
                "hand" if g in LIT.HAND else
                "hybrid" if g in LIT.HYBRID else "estimated")
        ev = str(st["events"]) if st["events"] else "—"
        ch = f"{st['chrom']:.1%}" if st["events"] else "—"
        fb = []
        if d["flags"] & F_TRANS_FB:
            fb.append("trans")
        if d["flags"] & F_QUAL_FB:
            fb.append("qual")
        if d["flags"] & F_INV_FB:
            fb.append("inv")
        fl = ("0x%02X" % d["flags"]) + (f" ({'+'.join(fb)})" if fb else "")
        a(f"| {g} | {tier} | {ev} | {ch} | {fl} | "
          f"{d['rhythmW']} | {d['microVar']} |")
    a("")
    a("## Attribution")
    a("")
    a("- McGill Billboard Dataset — CC0 (Miranda et al., mirror via mirdata).")
    a("- Isophonics annotations (Beatles, Queen, Carole King) — free research")
    a("  distribution, no formal license.")
    a("- Weimar Jazz Database — ODbL-1.0 + DbCL (Weiss & Goebl).")
    a("- TAVERN classical encodings — CC BY-SA 4.0 (Seyfarth et al.).")
    a("- Nottingham Database — original NMD free; cleaning repo GPL-3.0")
    a("  (jukedeck/nottingham-dataset).")
    a("- Only aggregate integer counts are redistributed; raw data stays in")
    a("  `tools/genre_data/cache/` (gitignored).")
    out_path.write_text("\n".join(md) + "\n")


def main():
    LIT.check()
    results = json.loads((HERE / "results.json").read_text())
    genres = build_genres(results)
    emit_header(genres, ROOT / "genre_data.h")
    emit_markdown(genres, results, ROOT / "GENRE_DATA.md")

    print(f"{'genre':12} {'trans row0':40} flags")
    for g in LIT.GENRE_ORDER:
        d = genres[g]
        print(f"{g:12} {str(d['trans'][0]):40} 0x{d['flags']:02X}")
    print("-> genre_data.h, GENRE_DATA.md")


if __name__ == "__main__":
    main()
